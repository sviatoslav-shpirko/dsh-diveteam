async function main() {
  const roles = loadRoles(rolesDir, coreMemoryPath)
  const sortedRoles = [...roles.values()].sort((a, b) => a.order - b.order || a.id.localeCompare(b.id))
  const orderedIds = sortedRoles.map((r) => r.id)

  // 1. Generate bundle patch: packages/dsh-dispatcher/cordis.patch.yml
  const bundleLines = [
    '# Auto-generated by scripts/sync-roles.mjs — DO NOT EDIT MANUALLY',
    '# Contains the DiveTeam Agent Presets (shturman, arch, dev, qa, sre, reg + custom roles)',
    '# compiled from roles/*.md + vault/memory/CORE.md, plus @diveteam/dsh-dispatcher.',
    '- insert:',
  ]

  for (const role of sortedRoles) {
    bundleLines.push(...buildRolePresetLines(role, 4))
  }

  bundleLines.push(
    `    - id: diveteam-dispatcher`,
    `      name: '@diveteam/dsh-dispatcher'`,
    `      config:`,
    `        projectRoot: ${rootDir}`,
    `        maxHeavyWorkers: 3`,
    `        maxQaRetries: 2`,
    `        maxDailyTokens: 2000000`,
    `        hostLockPath: /tmp/diveteam-host.lock`,
    '',
  )

  await fs.writeFile(outputPatchPath, bundleLines.join('\n'), 'utf8')
  console.log(`[sync-roles] Generated bundle patch ${outputPatchPath} (${orderedIds.length} presets + diveteam-dispatcher)`)

  // 2. Sync id-targeted overrides into ~/.dsh/profiles/deskweb/cordis.patch.yml (hot-reloaded by dsh)
  if (existsSync(profilePatchPath)) {
    const existingRaw = await fs.readFile(profilePatchPath, 'utf8')
    const normalized = existingRaw.replace(/\r\n/g, '\n')
    let baseSection = normalized
    let beginIdx = normalized.indexOf(BEGIN_MARKER)
    if (beginIdx === -1) {
      beginIdx = normalized.indexOf('# BEGIN FARVATER ROLES')
    }

    let endIdx = -1
    if (beginIdx !== -1) {
      const foundEnd = normalized.indexOf(END_MARKER, beginIdx)
      if (foundEnd !== -1) {
        endIdx = normalized.indexOf('\n', foundEnd)
        endIdx = endIdx === -1 ? normalized.length : endIdx + 1
      } else {
        const legacyEnd = normalized.indexOf('# END FARVATER ROLES', beginIdx)
        if (legacyEnd !== -1) {
          endIdx = normalized.indexOf('\n', legacyEnd)
          endIdx = endIdx === -1 ? normalized.length : endIdx + 1
        }
      }
    }

    if (beginIdx !== -1 && endIdx !== -1 && endIdx > beginIdx) {
      const before = normalized.slice(0, beginIdx).trimEnd()
      const after = normalized.slice(endIdx).trim()
      baseSection = after ? `${before}\n\n${after}` : before
    } else if (beginIdx !== -1) {
      baseSection = normalized.slice(0, beginIdx).trimEnd()
    } else {
      baseSection = normalized.trimEnd()
    }

    const profileRoleLines = [
      BEGIN_MARKER,
      `- id: ui-skill-explorer`,
      `  name: '@linxin666/dsh-client-ui-skill-explorer'`,
      `  config:`,
      `    customSkillDirs:`,
      `      - ${skillsDir}`,
      `- id: diveteam-dispatcher`,
      `  name: '@diveteam/dsh-dispatcher'`,
      `  config:`,
      `    projectRoot: ${rootDir}`,
      `    maxHeavyWorkers: 3`,
      `    maxQaRetries: 2`,
      `    maxDailyTokens: 2000000`,
      `    hostLockPath: /tmp/diveteam-host.lock`,
      `- id: diveteam-ui`,
      `  name: '@diveteam/dsh-client-diveteam-ui'`,
      `  config:`,
      `    projectRoot: ${rootDir}`,
    ]

    for (const role of sortedRoles) {
      profileRoleLines.push(...buildRolePresetLines(role, 0))
    }
    profileRoleLines.push(END_MARKER, '')

    const updatedProfilePatch = `${baseSection}\n\n${profileRoleLines.join('\n')}`
    await fs.writeFile(profilePatchPath, updatedProfilePatch, 'utf8')
    console.log(`[sync-roles] Synchronized profile patch ${profilePatchPath} (${orderedIds.length} presets + skill customSkillDirs)`)
  }
}

main().catch((err) => {
  console.error('[sync-roles] Failed:', err)
  process.exit(1)
})
