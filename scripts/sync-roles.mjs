import { existsSync } from 'node:fs'
import fs from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadRoles } from '../packages/dsh-dispatcher/lib/roles.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, '..')
const rolesDir = path.join(rootDir, 'roles')
const skillsDir = path.join(rootDir, 'skills')
const coreMemoryPath = path.join(rootDir, 'vault/memory/CORE.md')
const outputPatchPath = path.join(rootDir, 'packages/dsh-dispatcher/cordis.patch.yml')
const profilePatchPath = process.env.DSH_PROFILE_PATCH
  || path.join(process.env.DSH_HOME || path.join(os.homedir(), '.dsh'), 'profiles/deskweb/cordis.patch.yml')

const BEGIN_MARKER = '# BEGIN DIVETEAM ROLES (auto-generated by scripts/sync-roles.mjs)'
const END_MARKER = '# END DIVETEAM ROLES'

function indentBlock(text, spaces) {
  const pad = ' '.repeat(spaces)
  return text
    .replace(/\r\n/g, '\n')
    .split('\n')
    .map((line) => (line.length > 0 ? pad + line : ''))
    .join('\n')
}

